"""PDF exports of the company Reports page's analytical tabs (Initiating ATS, Average Time to Buss).

The rows are rebuilt here from the stored reports with the same rules the page uses (date range,
branch filter, "omit readings above 10.0 sec", NFPA flag only on Life Safety / Critical), so the
download is the authoritative report rather than a copy of whatever the browser happened to show.
"""
from __future__ import annotations

from datetime import date
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.services.report_pdf import BORDER, BRANCH_COLORS, BRANCH_LABELS, NAVY, RED, SLATE, TEXT_DIM, _header, _stat_tiles, _styles

NFPA_LIMIT_SEC = 10
NFPA_LIMITED_BRANCHES = {"life-safety", "critical"}
BRANCH_FILTERS = {"all", "life-safety", "critical", "equipment"}
# Same approximation the page uses: no dedicated "load served" field exists on an ATS yet.
BRANCH_LOAD_LABEL = {"life-safety": "Exit Lighting", "critical": "ICU / OR Suites", "equipment": "Mechanical / Elevator"}

_head = ParagraphStyle("aHead", fontName="Helvetica-Bold", fontSize=7, leading=9, textColor=colors.HexColor("#334155"), alignment=TA_LEFT)
_cell = ParagraphStyle("aCell", fontName="Helvetica", fontSize=7.5, leading=9.5, textColor=colors.HexColor("#0f172a"))
_bold = ParagraphStyle("aBold", parent=_cell, fontName="Helvetica-Bold")
_danger = ParagraphStyle("aDanger", parent=_cell, fontName="Helvetica-Bold", textColor=RED)
_note = ParagraphStyle("aNote", fontName="Helvetica", fontSize=7.5, leading=10, textColor=TEXT_DIM)


def _p(text, style=_cell):
    return Paragraph(escape(str(text)) if text not in (None, "") else "—", style)


def _display(value: date) -> str:
    return value.strftime("%b %d, %Y").replace(" 0", " ")


def event_type_label(report) -> str:
    if report.type == "gen-run":
        return "Generator Run"
    return report.event_type or ("Test" if report.type == "test" else "Emergency")


def is_exceeded(detail: dict) -> bool:
    seconds = detail.get("time_to_bus_sec")
    return detail.get("branch") in NFPA_LIMITED_BRANCHES and seconds is not None and seconds > NFPA_LIMIT_SEC


def time_to_buss_rows(reports, start: date, end: date, branch: str = "all", omit_over_limit: bool = False) -> list[tuple]:
    rows = []
    for report in reports:
        if not (start <= report.report_date <= end):
            continue
        for detail in report.ats_details or []:
            if branch != "all" and (detail.get("branch") or "equipment") != branch:
                continue
            seconds = detail.get("time_to_bus_sec")
            if omit_over_limit and seconds is not None and seconds > NFPA_LIMIT_SEC:
                continue
            rows.append((report, detail))
    return sorted(rows, key=lambda row: row[0].report_date)


def initiating_rows(reports, start: date, end: date) -> list:
    return sorted((r for r in reports if r.initiating_ats and start <= r.report_date <= end), key=lambda r: r.report_date)


def _grid(header: list[str], body: list[list], widths: list[float], accents: list | None = None) -> Table:
    table = Table([[Paragraph(h, _head) for h in header], *body], colWidths=[w * inch for w in widths], repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef2f7")),
        ("GRID", (0, 0), (-1, -1), 0.6, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f4f7fb")]),
    ]
    for i, accent in enumerate(accents or []):
        style.append(("LINEBEFORE", (0, i + 1), (0, i + 1), 2.5, accent))
    table.setStyle(TableStyle(style))
    return table


def _build(title: str, subtitle: str, story_body: list, company_name: str, logo_data, reseller_logo_data) -> bytes:
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=letter, topMargin=0, bottomMargin=0.55 * inch, leftMargin=0.6 * inch, rightMargin=0.6 * inch,
                            title=title, author="Critical Power Command")

    def footer(canvas, document):
        canvas.saveState()
        canvas.setStrokeColor(BORDER)
        canvas.line(0.6 * inch, 0.42 * inch, letter[0] - 0.6 * inch, 0.42 * inch)
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(TEXT_DIM)
        canvas.drawString(0.6 * inch, 0.28 * inch, f"Generated by CPC · {company_name} · {date.today().isoformat()}")
        canvas.drawRightString(letter[0] - 0.6 * inch, 0.28 * inch, f"Page {document.page}")
        canvas.restoreState()

    story = [_header(title, subtitle, "GENERATED", date.today(), logo_data, reseller_logo_data, True), Spacer(1, 12), *story_body]
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()


def build_time_to_buss_pdf(reports, company_name: str, start: date, end: date, branch: str = "all", omit_over_limit: bool = False,
                           logo_data: str | None = None, reseller_logo_data: str | None = None) -> bytes:
    rows = time_to_buss_rows(reports, start, end, branch, omit_over_limit)
    times = [d["time_to_bus_sec"] for _, d in rows if d.get("time_to_bus_sec") is not None]
    exceeded = sum(1 for _, d in rows if is_exceeded(d))
    filters = [f"Branch: {'All branches' if branch == 'all' else BRANCH_LABELS[branch].title()}"]
    if omit_over_limit:
        filters.append("Readings above 10.0 sec omitted")
    body = [
        _stat_tiles([
            ("TOTAL READINGS", str(len(rows)), NAVY),
            ("AVERAGE TIME TO BUSS", f"{sum(times) / len(times):.1f} sec" if times else "—", colors.white),
            ("FASTEST READING", f"{min(times):.1f} sec" if times else "—", colors.white),
            ("READINGS ABOVE 10.0 SEC", str(exceeded), RED),
        ]),
        Paragraph(escape(" · ".join(filters)), _note),
        Paragraph("Life Safety and Critical readings above 10.0 sec are flagged EXCEEDED for review against NFPA 110 Type 10 "
                  "transfer requirements. The Equipment branch is not held to the 10-sec requirement and is never flagged.", _note),
        Paragraph(f"ATS TRANSFER READINGS — TIME TO BUSS ({_display(start)} - {_display(end)})", _styles["sectionTitle"]),
    ]
    if rows:
        table_rows, accents = [], []
        for report, d in rows:
            seconds = d.get("time_to_bus_sec")
            flagged = is_exceeded(d)
            branch_key = d.get("branch")
            accents.append(BRANCH_COLORS.get(branch_key, SLATE))
            table_rows.append([
                _p(_display(report.report_date)),
                _p(d.get("switched_to_emergency") or report.time_label),
                _p(d.get("ats_name"), _bold),
                _p(BRANCH_LOAD_LABEL.get(branch_key)),
                _p(BRANCH_LABELS.get(branch_key, (branch_key or "").upper())),
                _p(event_type_label(report).upper()),
                Paragraph(f"{seconds if seconds is not None else '—'} sec{' EXCEEDED' if flagged else ''}", _danger if flagged else _cell),
                _p(f"{d['time_to_available_sec']} sec" if d.get("time_to_available_sec") is not None else None),
            ])
        body.append(_grid(["Date", "Time", "ATS", "Load Served", "Branch", "Event Type", "Time to Buss", "Time to Available"],
                          table_rows, [0.85, 0.8, 0.95, 1.05, 0.8, 0.85, 0.9, 0.8], accents))
    else:
        body.append(Paragraph("No ATS transfer readings match this date range and filters.", _note))
    return _build("Average Time to Buss Report", f"{company_name} — ATS transfer readings", body, company_name, logo_data, reseller_logo_data)


def build_initiating_ats_pdf(reports, company_name: str, system_names: dict[str, str], start: date, end: date,
                             logo_data: str | None = None, reseller_logo_data: str | None = None) -> bytes:
    rows = initiating_rows(reports, start, end)
    counts: dict[str, int] = {}
    for report in rows:
        counts[report.initiating_ats] = counts.get(report.initiating_ats, 0) + 1
    top = max(counts.items(), key=lambda item: item[1]) if counts else None
    body = [
        _stat_tiles([
            ("TOTAL EVENTS", str(len(rows)), NAVY),
            ("MOST FREQUENT INITIATOR", f"{top[0]} ({top[1]}x)" if top else "—", colors.white),
            ("TEST EVENTS", str(sum(1 for r in rows if r.type == "test")), colors.white),
            ("EMERGENCY EVENTS", str(sum(1 for r in rows if r.type == "ats-emergency")), RED),
        ]),
        Paragraph(f"EVENTS — INITIATING ATS BY DATE ({_display(start)} - {_display(end)})", _styles["sectionTitle"]),
    ]
    if rows:
        table_rows, accents = [], []
        for report in rows:
            detail = next((d for d in report.ats_details or [] if d.get("ats_name") == report.initiating_ats), None) or {}
            branch_key = detail.get("branch")
            accents.append(BRANCH_COLORS.get(branch_key, SLATE))
            table_rows.append([
                _p(_display(report.report_date)),
                _p(report.time_label),
                _p(report.initiating_ats, _bold),
                _p(BRANCH_LOAD_LABEL.get(branch_key) or system_names.get(report.system_id, report.system_id)),
                _p(BRANCH_LABELS.get(branch_key) if branch_key else None),
                _p(event_type_label(report).upper()),
                _p(len(report.ats_details) if report.ats_details else 1),
            ])
        body.append(_grid(["Date", "Time", "Initiating ATS", "Load Served", "Branch", "Event Type", "ATS Affected"],
                          table_rows, [0.95, 0.7, 1.25, 1.45, 0.9, 1.05, 0.7], accents))
    else:
        body.append(Paragraph("No initiating-ATS events in this date range.", _note))
    return _build("Initiating ATS Report", f"{company_name} — events by initiating ATS", body, company_name, logo_data, reseller_logo_data)
